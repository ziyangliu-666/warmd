#!/usr/bin/env bash
# Regenerate shim/stubs.c: every symbol the real libcuda exports gets a WEAK definition (a strong one in
# shim.c always wins): a jump to an implemented _v2/base variant for _ptsz/_ptds/old names, else a logging stub.
# Usage: tools/gen_stubs.sh [path to real libcuda.so.N]
set -e; cd "$(dirname "$0")/.."
REAL=${1:-$(readlink -f /usr/lib/x86_64-linux-gnu/libcuda.so.1)}
T=$(mktemp -d)
gcc -O0 -fPIC -shared shim/shim.c -o $T/s.so -Wl,--version-script=shim/shim.map -lpthread -ldl
nm -D --defined-only $T/s.so | awk '{print $3}' | sed 's/@.*//' | sort -u > $T/impl
nm -D --defined-only "$REAL" | awk '{print $3}' | sed 's/@.*//' | grep '^cu' | sort -u > $T/real
python3 - "$T" "$REAL" > shim/stubs.c <<'PY'
import sys
T, real = sys.argv[1], sys.argv[2]
impl = set(open(T + "/impl").read().split())
print(f"// generated by tools/gen_stubs.sh from {real}. Do not edit.")
print("// Every driver export gets a WEAK definition; a strong one in shim.c overrides it at link time.")
print("int wd_xstub(const char*);")
print("#define XS(n) __attribute__((weak)) int n(void) { return wd_xstub(#n); }")
print('#define AL(n, t) __asm__(".weak " #n "\\n.type " #n ",@function\\n" #n ":\\n\\tjmp " #t "@PLT\\n");')
na = ns = 0
for m in open(T + "/real").read().split():
    if m in impl: continue
    b = m
    for suf in ("_ptsz", "_ptds"):
        if b.endswith(suf): b = b[: -len(suf)]
    cands = [b, b + "_v2", b + "_v3"] if b != m else [b + "_v2", b + "_v3"]
    t = next((c for c in cands if c in impl), None)
    print(f"AL({m}, {t})" if t else f"XS({m})")
PY
echo "stubs: $(grep -c '^AL' shim/stubs.c) aliases, $(grep -c '^XS' shim/stubs.c) stubs"
rm -rf $T
